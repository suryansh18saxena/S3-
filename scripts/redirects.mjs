const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const htaccess = `# S3 Infrastructure — static site rules for Apache / LiteSpeed (e.g. Hostinger).
# Generated by scripts/redirects.mjs — edit that file, not this one.

Options -MultiViews
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  # Always use HTTPS and the bare domain.
  RewriteCond %{HTTPS} !=on [OR]
  RewriteCond %{HTTP_HOST} ^www\\. [NC]
  RewriteRule ^ https://s3infrastructure.com%{REQUEST_URI} [L,R=301]
</IfModule>

# Legacy WordPress URLs (permanent).
<IfModule mod_alias.c>
${redirects.map(([from, to]) => `  RedirectMatch 301 ^${esc(from)}/?$ ${to}`).join("\n")}
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
  Header always set X-Frame-Options "SAMEORIGIN"
  # Fingerprinted build assets never change.
  <If "%{REQUEST_URI} =~ m#^/_next/static/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
  # Images and fonts: long cache, revalidate monthly.
  <If "%{REQUEST_URI} =~ m#^/(media|brand)/#">
    Header set Cache-Control "public, max-age=2592000"
  </If>
  <FilesMatch "\\.html$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>

<IfModule mod_mime.c>
  AddType image/avif .avif
  AddType image/webp .webp
  AddType application/manifest+json .webmanifest
</IfModule>
`;

const netlify = `# Generated by scripts/redirects.mjs — Netlify / Cloudflare Pages format.
${redirects.flatMap(([from, to]) => [`${from} ${to} 301`, `${from}/ ${to} 301`]).join("\n")}
`;

writeFileSync(path.join(root, "public/.htaccess"), htaccess);
writeFileSync(path.join(root, "public/_redirects"), netlify);
